#!/usr/bin/env node
/**
 * Builds the app's design-system CSS from the synced files in design-system/.
 *
 *   design-system/tokens.json            → src/styles/generated/tokens.css
 *   design-system/components/bundle.css  → src/styles/generated/components.css
 *
 * tokens.css: every colour token for Light, Dark (explicit data-theme) and
 * System (prefers-color-scheme), plus spacing, radius, size, type and a
 * Tailwind `@theme inline` block so utilities like `bg-surface` exist.
 *
 * components.css: the design system's component classes (cc-*), with
 * physical left/right rules rewritten to logical properties so they work
 * in right-to-left languages.
 *
 * Run with `pnpm tokens`. Never edit the generated files by hand.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = (p) => join(root, "design-system", p);
const out = join(root, "src", "styles", "generated");
mkdirSync(out, { recursive: true });

const HEADER = "/* GENERATED by scripts/build-tokens.mjs from design-system/. Do not edit. */\n";
const t = JSON.parse(readFileSync(src("tokens.json"), "utf8"));

// ---------- colours (+ themed shadows) ----------
const themed = [
  ...t.color.tokens.map((c) => ({ name: c.name, light: c.value.light, dark: c.value.dark })),
  ...t.shadow.tokens.map((s) => ({ name: s.name, light: s.value.light, dark: s.value.dark })),
];
const block = (mode) => themed.map((c) => `  --${c.name}: ${c[mode]};`).join("\n");

// ---------- fixed scales ----------
const fixed = [...t.spacing.tokens, ...t.radius.tokens, ...t.size.tokens].map((x) => `  --${x.name}: ${x.value};`);

const fam = t.type.families;
fixed.push(`  --font-sans: ${fam.sans};`, `  --font-mono: ${fam.mono};`);
// Arabic falls back to the platform's Arabic system font with the same metrics feel.
fixed.push(`  --font-sans-ar: "SF Arabic", "Geeza Pro", "Segoe UI", "Noto Sans Arabic", ${fam.sans};`);

const styles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: s.family || g.family })));
for (const s of styles) {
  fixed.push(`  --text-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family});`);
}

// ---------- type classes (match the design system's .large-title etc.) ----------
const typeClasses = styles
  .map(
    (s) =>
      `.${s.name}{font-family:var(--font-${s.family});font-size:${s.fontSize};line-height:${s.lineHeight};font-weight:${s.fontWeight};letter-spacing:${s.letterSpacing}${s.name === "eyebrow" ? ";text-transform:uppercase" : ""}}`,
  )
  .join("\n");

// ---------- Tailwind theme mapping ----------
// Reset Tailwind's defaults so only tokens exist (no bg-red-500, no rounded-3xl…).
// Colours point at the themed variables (inline, so they follow the theme).
const twInline = [
  "  --color-*: initial;",
  "  --shadow-*: initial;",
  "  --color-transparent: transparent;",
  "  --color-current: currentColor;",
  ...t.color.tokens.map((c) => `  --color-${c.name}: var(--${c.name});`),
  ...t.shadow.tokens.map((s) => `  --shadow-${s.name.replace("shadow-", "")}: var(--${s.name});`),
];
// Names that already match the design system's variables get literal values,
// so Tailwind's own variable and the design system's are the same thing.
const tw = [
  "  --radius-*: initial;",
  "  --text-*: initial;",
  "  --font-*: initial;",
  ...t.radius.tokens.map((r) => `  --${r.name}: ${r.value};`),
  `  --font-sans: ${fam.sans};`,
  `  --font-mono: ${fam.mono};`,
  // 4px base: p-1 = 4px … p-12 = 48px, matching space-1 … space-12.
  "  --spacing: 4px;",
  "  --spacing-control: var(--control-height);",
  "  --spacing-control-sm: var(--control-height-sm);",
  "  --spacing-avatar: var(--avatar);",
];

const dark = block("dark");
const tokensCss = `${HEADER}
/* Light is the default. */
:root {
${block("light")}
  color-scheme: light;
}

/* System: follow the OS unless the person picked Light. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}

/* Explicit Dark. */
:root[data-theme="dark"] {
${dark}
  color-scheme: dark;
}

:root {
${fixed.join("\n")}
}

:lang(ar) { --font-sans: var(--font-sans-ar); }

${typeClasses}

@theme inline {
${twInline.join("\n")}
}

@theme {
${tw.join("\n")}
}
`;
writeFileSync(join(out, "tokens.css"), tokensCss);

// ---------- components: physical → logical ----------
let css = readFileSync(src("components/bundle.css"), "utf8");
const swaps = [
  [/margin-left:/g, "margin-inline-start:"],
  [/margin-right:/g, "margin-inline-end:"],
  [/padding-left:/g, "padding-inline-start:"],
  [/padding-right:/g, "padding-inline-end:"],
  [/border-left:/g, "border-inline-start:"],
  [/border-right:/g, "border-inline-end:"],
  [/border-left-/g, "border-inline-start-"],
  [/border-right-/g, "border-inline-end-"],
  [/text-align:left/g, "text-align:start"],
  [/text-align:right/g, "text-align:end"],
  [/([;{])left:/g, "$1inset-inline-start:"],
  [/([;{])right:/g, "$1inset-inline-end:"],
];
for (const [re, to] of swaps) css = css.replace(re, to);
writeFileSync(join(out, "components.css"), `${HEADER}${css}`);

console.log("✓ tokens.css and components.css generated");
